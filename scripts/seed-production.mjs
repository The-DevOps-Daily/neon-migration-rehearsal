// Build the "production" database on the project's main branch: a shop with 500,000
// customers and 4,000,000 orders over three years, with the small flaws real data has.
//
//   node scripts/seed-production.mjs
//
// Everything is generated inside Postgres with generate_series, so the client only sends SQL.

import pg from 'pg';
import { need } from './lib/env.mjs';

const client = new pg.Client({ connectionString: need('DATABASE_URL') });
await client.connect();

const step = async (label, sql) => {
  const started = Date.now();
  const res = await client.query(sql);
  console.log(`${label.padEnd(44)} ${((Date.now() - started) / 1000).toFixed(1)}s${res.rowCount ? `  (${res.rowCount.toLocaleString('en-US')} rows)` : ''}`);
};

await step('drop old tables', 'DROP TABLE IF EXISTS orders_archive, orders, customers CASCADE');

await step(
  'create schema',
  `CREATE TABLE customers (
     id         bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
     email      text NOT NULL,
     phone      text,
     created_at timestamptz NOT NULL DEFAULT now()
   );
   CREATE TABLE orders (
     id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     customer_id  bigint NOT NULL REFERENCES customers (id),
     amount_cents integer NOT NULL,
     status       text NOT NULL,
     created_at   timestamptz NOT NULL DEFAULT now()
   );
   CREATE INDEX orders_customer_id_idx ON orders (customer_id);
   CREATE TABLE orders_archive (
     id           bigint PRIMARY KEY,
     customer_id  bigint NOT NULL,
     amount_cents integer NOT NULL,
     status       text NOT NULL,
     created_at   timestamptz NOT NULL
   );`,
);

// Real data drift: one signup in 400 reused an address with different capitals (the app
// lowercased emails only from 2025), and phone was optional for the first year.
await step(
  'insert 500,000 customers',
  `INSERT INTO customers (email, phone, created_at)
   SELECT CASE WHEN i % 400 = 0 THEN 'User' || (i - 1) || '@Example.com'
               ELSE 'user' || i || '@example.com' END,
          CASE WHEN i <= 15000 THEN NULL
               ELSE '+1555' || lpad((i % 10000000)::text, 7, '0') END,
          now() - interval '3 years' + (i::float / 500000) * interval '3 years'
   FROM generate_series(1, 500000) AS i`,
);

await step(
  'insert 4,000,000 orders',
  `INSERT INTO orders (customer_id, amount_cents, status, created_at)
   SELECT 1 + (hashint4(i) & 2147483647) % 500000,
          500 + (hashint4(i + 7) & 2147483647) % 50000,
          (ARRAY['paid', 'shipped', 'shipped', 'shipped', 'refunded'])[1 + (hashint4(i + 13) & 2147483647) % 5],
          now() - interval '3 years' + (i::float / 4000000) * interval '3 years'
   FROM generate_series(1, 4000000) AS i`,
);

await step('analyze', 'ANALYZE customers; ANALYZE orders; ANALYZE orders_archive');

const { rows } = await client.query(
  `SELECT (SELECT count(*) FROM customers) AS customers,
          (SELECT count(*) FROM orders) AS orders,
          (SELECT count(*) FROM (SELECT lower(email) FROM customers GROUP BY 1 HAVING count(*) > 1) d) AS duplicate_emails,
          (SELECT count(*) FROM customers WHERE phone IS NULL) AS null_phones,
          pg_size_pretty(pg_total_relation_size('orders')) AS orders_size,
          pg_size_pretty(pg_database_size(current_database())) AS database_size`,
);
console.log(rows[0]);
await client.end();
